#!/usr/bin/env node
// Download the studio's license-cleared (CC0) library files listed in assets/library/polyhaven.manifest.json from
// Poly Haven (https://polyhaven.com, all assets CC0 1.0) and record provenance (URL, bytes, SHA-256, licence) in
// assets/library/polyhaven.lock.json. Re-running skips files whose hash already matches the lock.
//   node tools/fetch-assets.mjs            # fetch everything in the manifest
//   node tools/fetch-assets.mjs red_brick_03 belfast_sunset_puresky   # only these ids
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = path.join(ROOT, 'assets/library/polyhaven.manifest.json');
const LOCK = path.join(ROOT, 'assets/library/polyhaven.lock.json');
const UA = { 'User-Agent': 'whatif-shorts-studio/1.0 (asset fetch; CC0 Poly Haven)' };
const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
const lock = fs.existsSync(LOCK) ? JSON.parse(fs.readFileSync(LOCK, 'utf8')) : { note: 'Generated by tools/fetch-assets.mjs', license: 'CC0 1.0 Universal (Poly Haven)', files: {} };
const only = new Set(process.argv.slice(2));
const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
// Poly Haven map names → our file suffixes (diffuse, OpenGL normal, packed AO/roughness/metal).
const MAPS = { diff: 'Diffuse', nor_gl: 'nor_gl', arm: 'arm' };

async function get(url) {
  for (let attempt = 0; attempt < 4; attempt++) {
    try { const r = await fetch(url, { headers: UA }); if (!r.ok) throw new Error(`HTTP ${r.status}`); return Buffer.from(await r.arrayBuffer()); }
    catch (e) { if (attempt === 3) throw new Error(`${url}: ${e.message}`); await new Promise((res) => setTimeout(res, 1500 * (attempt + 1))); }
  }
}

let fetched = 0, kept = 0;
for (const item of manifest.assets) {
  if (only.size && !only.has(item.id)) continue;
  const files = JSON.parse((await get(`https://api.polyhaven.com/files/${item.id}`)).toString('utf8'));
  const jobs = item.type === 'hdri'
    ? [{ key: `${item.id}/hdri`, url: files.hdri[item.res].hdr.url, dest: `assets/library/hdri/${item.id}_${item.res}.hdr` }]
    : (item.maps ?? Object.keys(MAPS)).map((m) => ({ key: `${item.id}/${m}`, url: files[MAPS[m]][item.res].jpg.url, dest: `assets/library/textures/pbr/${item.id}/${item.id}_${m}_${item.res}.jpg` }));
  for (const job of jobs) {
    const abs = path.join(ROOT, job.dest), prev = lock.files[job.key];
    if (prev && prev.url === job.url && fs.existsSync(abs) && sha(fs.readFileSync(abs)) === prev.sha256) { kept++; continue; }
    const buf = await get(job.url);
    fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, buf);
    lock.files[job.key] = { id: item.id, type: item.type, dest: job.dest, url: job.url, bytes: buf.length, sha256: sha(buf), fetchedAt: new Date().toISOString(),
      credit: `Poly Haven — ${item.id} (https://polyhaven.com/a/${item.id})`, license: 'CC0 1.0 Universal (public domain dedication), https://polyhaven.com/license' };
    fetched++; console.log(`fetched ${job.dest} (${(buf.length / 1e6).toFixed(2)} MB)`);
  }
}
fs.writeFileSync(LOCK, JSON.stringify(lock, null, 2) + '\n');
const total = Object.values(lock.files).reduce((s, f) => s + f.bytes, 0);
console.log(`done: ${fetched} fetched, ${kept} unchanged | library total ${(total / 1e6).toFixed(1)} MB | lock ${path.relative(ROOT, LOCK)}`);
